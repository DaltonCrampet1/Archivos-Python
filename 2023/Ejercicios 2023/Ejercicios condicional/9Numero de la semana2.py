numero = input("Escriba el dia de la semana: ")

if numero == "lunes":
    print("Hoy comienza la semana. Animo!")
if numero == "viernes":
    print("Ya casi termina!")
if numero == "sabado" or numero == "domingo":
    print("Siiii! Fin de semana!")
if numero == "martes" or numero == "miercoles" or numero == "jueves":
    print("Vamos que se puede!")
